#!/usr/bin/env bash
# headrun engine adapter: stub — deterministic Markdown response, no LLM. For development and testing.
# headrun-keys: stub_sleep, stub_exit, stub_outcome, stub_silent

set -o errexit -o nounset -o pipefail

ADAPTER_ACTION="${1:-run}"

case "${ADAPTER_ACTION}" in
  check)
    printf 'built-in (no external dependencies)\n'
    exit 0
    ;;
  run) ;;
  *)
    printf 'stub: unknown action %s\n' "${ADAPTER_ACTION}" >&2
    exit 2
    ;;
esac

STUB_SLEEP_SECONDS="${HEADRUN_FM_STUB_SLEEP:-0}"
STUB_EXIT_CODE="${HEADRUN_FM_STUB_EXIT:-0}"
STUB_OUTCOME="${HEADRUN_FM_STUB_OUTCOME:-completed}"
STUB_SILENT="${HEADRUN_FM_STUB_SILENT:-no}"

printf 'stub: job %s starting in %s\n' "${HEADRUN_JOB_ID}" "${PWD}"
printf 'stub: prompt is %s lines\n' "$(wc -l < "${HEADRUN_PROMPT}")"

STEP_NUMBER=0
while (( STEP_NUMBER < STUB_SLEEP_SECONDS )); do
  STEP_NUMBER=$(( STEP_NUMBER + 1 ))
  printf 'stub: working (%s/%s)\n' "${STEP_NUMBER}" "${STUB_SLEEP_SECONDS}"
  sleep 1
done

REQUEST_WORD_COUNT="$(wc -w < "${HEADRUN_REQUEST}")"
REQUEST_LINE_COUNT="$(wc -l < "${HEADRUN_REQUEST}")"

if [[ "${STUB_SILENT}" != "yes" ]]; then
  {
    printf 'Outcome: %s\n\n' "${STUB_OUTCOME}"
    printf '# Stub response: %s\n\n' "${HEADRUN_TITLE}"
    printf 'This response was generated by the **stub** engine. No LLM was involved.\n\n'
    printf -- '- Job: `%s`\n' "${HEADRUN_JOB_ID}"
    printf -- '- Generated: %s\n' "$(date '+%Y-%m-%d %H:%M:%S %Z')"
    printf -- '- Working directory: `%s`\n' "${HEADRUN_WORKDIR}"
    printf -- '- Request: %s lines, %s words\n' "${REQUEST_LINE_COUNT}" "${REQUEST_WORD_COUNT}"
    printf -- '- Model: %s\n' "${HEADRUN_MODEL:-(none)}"
    printf -- '- Permissions: %s\n' "${HEADRUN_PERMISSIONS}"
  } > "${HEADRUN_RESPONSE}"
fi

printf 'engine_version=stub\n' >> "${HEADRUN_ENGINE_META}"
printf 'stub: finished with exit code %s\n' "${STUB_EXIT_CODE}"
exit "${STUB_EXIT_CODE}"
